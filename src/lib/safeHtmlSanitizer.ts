import katex from 'katex';

/**
 * Sanitizes an HTML string to prevent XSS attacks while preserving
 * rich typography, tables, images, styling, and formatting tags.
 */
export function sanitizeHtml(rawHtml: string): string {
  if (!rawHtml) return '';

  // 1. Remove dangerous script and iframe tags completely
  let clean = rawHtml
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, '')
    .replace(/<iframe\b[^<]*(?:(?!<\/iframe>)<[^<]*)*<\/iframe>/gi, '')
    .replace(/<object\b[^<]*(?:(?!<\/object>)<[^<]*)*<\/object>/gi, '')
    .replace(/<embed\b[^<]*(?:(?!<\/embed>)<[^<]*)*<\/embed>/gi, '')
    .replace(/<form\b[^<]*(?:(?!<\/form>)<[^<]*)*<\/form>/gi, '');

  // 2. Remove inline event handlers (onclick, onerror, onload, etc.)
  clean = clean.replace(/\son[a-zA-Z]+\s*=\s*(['"]).*?\1/gi, '');
  clean = clean.replace(/\son[a-zA-Z]+\s*=\s*[^ >]+/gi, '');

  // 3. Remove javascript: links and vbscript: links
  clean = clean.replace(/href\s*=\s*(['"])javascript:[^'"]*\1/gi, 'href="#"');
  clean = clean.replace(/src\s*=\s*(['"])javascript:[^'"]*\1/gi, 'src=""');

  return clean;
}

/**
 * Scans HTML content and renders LaTeX expressions:
 * - Block math: $$ ... $$
 * - Inline math: \( ... \) or $ ... $ (with lookaround to avoid currency like $100)
 * - HTML math spans: <span data-latex="..."></span>
 */
export function renderKaTeXInHtml(content: string): string {
  if (!content) return '';

  let processed = content;

  // 1. Process custom data-latex spans generated by equation modal
  processed = processed.replace(
    /<span[^>]*data-latex="([^"]+)"[^>]*>.*?<\/span>/gi,
    (_, latex) => {
      try {
        const decoded = decodeURIComponent(latex);
        return katex.renderToString(decoded, {
          throwOnError: false,
          displayMode: false
        });
      } catch {
        return `[LaTeX: ${latex}]`;
      }
    }
  );

  // 2. Process block math $$...$$
  processed = processed.replace(/\$\$([\s\S]+?)\$\$/g, (_, latex) => {
    try {
      return `<div class="my-4 py-2 text-center overflow-x-auto">${katex.renderToString(latex.trim(), {
        throwOnError: false,
        displayMode: true
      })}</div>`;
    } catch {
      return `$$${latex}$$`;
    }
  });

  // 3. Process inline math \( ... \)
  processed = processed.replace(/\\\(([\s\S]+?)\\\)/g, (_, latex) => {
    try {
      return katex.renderToString(latex.trim(), {
        throwOnError: false,
        displayMode: false
      });
    } catch {
      return `\\(${latex}\\)`;
    }
  });

  // 4. Process inline math $...$ when surrounded by valid non-dollar chars
  processed = processed.replace(/(^|[^\\])\$([^\$\n]+?)\$/g, (match, prefix, latex) => {
    // Avoid currency numbers like $50 or $100
    if (/^\d+(\.\d+)?$/.test(latex.trim())) {
      return match;
    }
    try {
      const rendered = katex.renderToString(latex.trim(), {
        throwOnError: false,
        displayMode: false
      });
      return `${prefix}${rendered}`;
    } catch {
      return match;
    }
  });

  return processed;
}

/**
 * Counts words from HTML or plain text.
 */
export function countWords(content: string): number {
  if (!content) return 0;
  // Strip HTML tags
  const text = content.replace(/<[^>]*>/g, ' ').replace(/\s+/g, ' ').trim();
  if (!text) return 0;
  return text.split(/\s+/).length;
}

/**
 * Counts characters without HTML tags.
 */
export function countCharacters(content: string): number {
  if (!content) return 0;
  const text = content.replace(/<[^>]*>/g, '').trim();
  return text.length;
}

/**
 * Calculates estimated read time in minutes (approx. 200 words per minute).
 */
export function calculateReadTime(content: string): number {
  const words = countWords(content);
  return Math.max(1, Math.ceil(words / 200));
}

/**
 * Converts markdown-style content to clean HTML if not already HTML,
 * then sanitizes and parses KaTeX formulas.
 */
export function formatArticleContent(raw: string): string {
  if (!raw) return '';

  // 1. Normalisasi string escape literal '\n' atau '\r\n' menjadi karakter baris baru sesungguhnya
  const normalized = raw
    .replace(/\\r\\n/g, '\n')
    .replace(/\\n/g, '\n')
    .replace(/\r\n/g, '\n');

  let html = normalized;

  // Check if content appears to be raw markdown rather than HTML
  const hasHtmlTags = /<[a-z][\s\S]*>/i.test(normalized);
  if (!hasHtmlTags) {
    html = normalized
      // Headers
      .replace(/^### (.*$)/gim, '<h3 class="text-base font-bold text-slate-900 mt-4 mb-2">$1</h3>')
      .replace(/^## (.*$)/gim, '<h2 class="text-lg font-black text-slate-900 mt-6 mb-3 border-b pb-1">$1</h2>')
      .replace(/^# (.*$)/gim, '<h1 class="text-xl font-black text-slate-900 mt-6 mb-3">$1</h1>')
      // Horizontal Rule
      .replace(/^---$/gim, '<hr class="my-6 border-slate-200" />')
      // Bold & Italic
      .replace(/\*\*\*(.*?)\*\*\*/g, '<strong><em>$1</em></strong>')
      .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
      .replace(/\*(.*?)\*/g, '<em>$1</em>')
      // Bullet lists
      .replace(/^\- (.*$)/gim, '<li class="ml-4 list-disc">$1</li>')
      // Numbered lists
      .replace(/^\d+\. (.*$)/gim, '<li class="ml-4 list-decimal">$1</li>')
      // Paragraphs
      .split('\n\n')
      .map(p => {
        const trimmed = p.trim();
        if (!trimmed) return '';
        if (trimmed.startsWith('<h') || trimmed.startsWith('<hr') || trimmed.startsWith('<li')) {
          return trimmed;
        }
        return `<p class="my-2">${trimmed.replace(/\n/g, '<br/>')}</p>`;
      })
      .join('');
  }

  const clean = sanitizeHtml(html);
  return renderKaTeXInHtml(clean);
}

